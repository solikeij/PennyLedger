-- FRESH INSTALL ONLY: creates the final schema and inserts default lookup data.
-- The DROP below permanently removes every existing account and transaction.
-- Never run this file to update an existing database; use scripts/migrate.php.
DROP DATABASE IF EXISTS PersonalBudget_db;

CREATE DATABASE PersonalBudget_db;
USE PersonalBudget_db;

-- =========================================
-- USERS
-- =========================================

-- Account credentials, access role, status, and optional profile details.
CREATE TABLE Users(
    user_id INT PRIMARY KEY AUTO_INCREMENT,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    -- Password hash generated by PHP password_hash(); never store a plain-text password.
    password VARCHAR(255) NOT NULL,
    email_verified TINYINT(1) NOT NULL DEFAULT 0,
    role ENUM('user', 'admin') NOT NULL DEFAULT 'user',
    status ENUM('active', 'inactive', 'suspended', 'deleted') NOT NULL DEFAULT 'active',
    phone VARCHAR(30) NULL,
    photo_path VARCHAR(255) NULL,
    monthly_income_estimate DECIMAL(10,2) NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL,
    last_login_at DATETIME NULL,
    deleted_at DATETIME NULL
);

-- =========================================
-- ACTIVITY TYPES
-- =========================================

-- Lookup labels and stable codes for the legacy activity log.
CREATE TABLE Activity_Types(
    activity_type_id INT PRIMARY KEY AUTO_INCREMENT,
    activity_name VARCHAR(100) NOT NULL,
    code VARCHAR(50) NULL,
    UNIQUE KEY uq_activity_type_code (code)
);

-- =========================================
-- ACTIVITY LOGS
-- =========================================

-- Legacy activity records retained for compatibility with older installations.
-- Current private activity and authentication events have separate tables below.
CREATE TABLE Activity_Logs(
    activity_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    activity_type_id INT NOT NULL,
    activity_description VARCHAR(100) NOT NULL,
    activity_date DATETIME NOT NULL,

    FOREIGN KEY (user_id) REFERENCES Users(user_id),
    FOREIGN KEY (activity_type_id) REFERENCES Activity_Types(activity_type_id)
);

-- =========================================
-- TRANSACTION TYPES
-- =========================================

-- Identifies whether a transaction or category represents income or expense.
CREATE TABLE TransactionTypes(
    transaction_type_id INT PRIMARY KEY AUTO_INCREMENT,
    type_name VARCHAR(100) NOT NULL,
    code VARCHAR(30) NULL,
    UNIQUE KEY uq_transaction_type_code (code)
);

-- =========================================
-- CATEGORIES
-- =========================================

-- Category definitions linked to an income or expense transaction type.
CREATE TABLE Categories(
    category_id INT PRIMARY KEY AUTO_INCREMENT,
    category_name VARCHAR(100) NOT NULL,
    transaction_type_id INT NOT NULL,

    FOREIGN KEY (transaction_type_id) REFERENCES TransactionTypes(transaction_type_id)
);

-- =========================================
-- BUDGETS
-- =========================================

-- Spending limits owned by a user, linked to a category and date range.
CREATE TABLE Budgets(
    budget_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    category_id INT NOT NULL,
    budget_amount DECIMAL(10, 2) NOT NULL,

    -- Supports daily, weekly, and monthly budgets
    budget_period ENUM('daily', 'weekly', 'monthly') NOT NULL,

    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_at DATETIME NOT NULL,

    FOREIGN KEY (user_id) REFERENCES Users(user_id),
    FOREIGN KEY (category_id) REFERENCES Categories(category_id)
);

-- =========================================
-- PAYMENT METHODS
-- =========================================

-- Payment-method records referenced by transactions and user wallets.
CREATE TABLE Payment_Methods(
    payment_method_id INT PRIMARY KEY AUTO_INCREMENT,
    payment_method_name VARCHAR(50) NOT NULL
);

-- =========================================
-- TRANSACTIONS
-- =========================================

-- Income and expense entries belonging to a user.
-- Foreign keys link each entry to its category, type, and payment method.
CREATE TABLE Transactions(
    transaction_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    category_id INT NOT NULL,
    transaction_type_id INT NOT NULL,
    amount DECIMAL(10, 2) NOT NULL,
    description VARCHAR(150) NOT NULL,
    transaction_date DATE NOT NULL,
    payment_method_id INT NOT NULL,
    created_at DATETIME NOT NULL,
    -- Archiving preserves the record while allowing it to be hidden from the main history.
    archived TINYINT(1) NOT NULL DEFAULT 0,
    archived_at DATETIME NULL,
    -- Supports per-user date filtering and active/archive views.
    INDEX idx_transactions_user_date (user_id, transaction_date),
    INDEX idx_transactions_user_archived (user_id, archived),

    FOREIGN KEY (user_id) REFERENCES Users(user_id),
    FOREIGN KEY (category_id) REFERENCES Categories(category_id),
    FOREIGN KEY (transaction_type_id) REFERENCES TransactionTypes(transaction_type_id),
    FOREIGN KEY (payment_method_id) REFERENCES Payment_Methods(payment_method_id)
);

-- =========================================
-- GOAL STATUSES
-- =========================================

-- Lookup values describing a savings goal: active, completed, or paused.
CREATE TABLE Goal_Statuses(
    status_id INT PRIMARY KEY AUTO_INCREMENT,
    status_name VARCHAR(100) NOT NULL,
    code VARCHAR(30) NULL,
    UNIQUE KEY uq_goal_status_code (code)
);

-- =========================================
-- FINANCIAL GOALS
-- =========================================

-- Savings targets owned by a user, with a deadline and current status.
CREATE TABLE Financial_Goals(
    goal_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    goal_name VARCHAR(100) NOT NULL,
    target_amount DECIMAL(10, 2) NOT NULL,
    target_date DATE NOT NULL,
    status_id INT NOT NULL,
    created_at DATETIME NOT NULL,

    FOREIGN KEY (user_id) REFERENCES Users(user_id),
    FOREIGN KEY (status_id) REFERENCES Goal_Statuses(status_id)
);

-- =========================================
-- GOAL CONTRIBUTIONS
-- =========================================

-- Individual savings contributions linked to a goal; the goal identifies the owner.
CREATE TABLE Goal_Contribution(
    contribution_id INT PRIMARY KEY AUTO_INCREMENT,
    goal_id INT NOT NULL,
    amount DECIMAL(10, 2) NOT NULL,
    contribution_date DATE NOT NULL,
    description VARCHAR(100) NOT NULL,

    FOREIGN KEY (goal_id) REFERENCES Financial_Goals(goal_id)
);

-- =========================================
-- OTP CODES
-- =========================================

-- Time-limited verification codes; the API checks expiry and whether a code was used.
CREATE TABLE Otp_Codes(
    otp_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    code VARCHAR(6) NOT NULL,

    -- Used for email verification
    purpose VARCHAR(50) NOT NULL,

    expires_at DATETIME NOT NULL,
    used TINYINT(1) NOT NULL DEFAULT 0,

    FOREIGN KEY (user_id) REFERENCES Users(user_id)
);

-- =========================================
-- LOGIN TOKENS
-- =========================================

-- Authenticated sessions. The token column stores a SHA-256 hash, not the bearer token.
-- Fresh installs start empty; revoking old plain-text tokens belongs in an upgrade migration.
CREATE TABLE Tokens(
    token_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    token VARCHAR(255) NOT NULL UNIQUE,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at DATETIME NOT NULL,
    INDEX idx_tokens_expiry (expires_at),

    FOREIGN KEY (user_id) REFERENCES Users(user_id)
);

-- Application-wide settings stored as key/value pairs.
CREATE TABLE App_Settings (
    setting_key VARCHAR(100) PRIMARY KEY,
    setting_value TEXT NOT NULL
);

-- Generated report logs and archived snapshots.
CREATE TABLE Report_Logs (
    report_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    report_name VARCHAR(200) NOT NULL,
    report_type VARCHAR(30) NOT NULL,
    report_range VARCHAR(30) NOT NULL,
    report_period VARCHAR(100) NOT NULL,
    snapshot_json JSON NOT NULL,
    generated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    archived TINYINT(1) NOT NULL DEFAULT 0,
    FOREIGN KEY (user_id) REFERENCES Users(user_id),
    INDEX idx_report_logs_user (user_id, generated_at)
);

-- Named wallets belonging to a user. Each wallet has a unique payment-method reference.
CREATE TABLE Wallets (
    wallet_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    payment_method_id INT NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    kind ENUM('bank', 'digital', 'cash', 'other') NOT NULL,
    expense_type VARCHAR(100) NOT NULL DEFAULT 'Other',
    -- Legacy balance field retained for compatibility, not a live bank balance.
    balance DECIMAL(10,2) NOT NULL DEFAULT 0,
    is_default TINYINT(1) NOT NULL DEFAULT 0,
    deleted_at DATETIME NULL,
    FOREIGN KEY (user_id) REFERENCES Users(user_id),
    FOREIGN KEY (payment_method_id) REFERENCES Payment_Methods(payment_method_id)
);

-- Legacy transfer records retained for schema compatibility.
-- The current API no longer supports wallet balance transfers.
CREATE TABLE Wallet_Transfers (
    transfer_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    from_wallet_id INT NOT NULL,
    to_wallet_id INT NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES Users(user_id),
    FOREIGN KEY (from_wallet_id) REFERENCES Wallets(wallet_id),
    FOREIGN KEY (to_wallet_id) REFERENCES Wallets(wallet_id)
);

-- Legacy balance-adjustment records retained for schema compatibility.
CREATE TABLE Wallet_Adjustments (
    adjustment_id INT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    wallet_id INT NOT NULL,
    previous_balance DECIMAL(14,2) NOT NULL,
    new_balance DECIMAL(14,2) NOT NULL,
    amount DECIMAL(14,2) NOT NULL,
    reason VARCHAR(200) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES Users(user_id),
    FOREIGN KEY (wallet_id) REFERENCES Wallets(wallet_id)
);

-- Stores write-request results so retries with the same user and request key can be replayed.
-- The fingerprint identifies the request payload; the saved response records its outcome.
CREATE TABLE Write_Requests (
    user_id INT NOT NULL,
    request_key VARCHAR(80) NOT NULL,
    fingerprint CHAR(64) NOT NULL,
    status_code INT NULL,
    response_json MEDIUMTEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(user_id, request_key),
    FOREIGN KEY (user_id) REFERENCES Users(user_id)
);

-- Queue of uploaded file paths awaiting removal, allowing failed cleanup to be retried.
CREATE TABLE File_Cleanup (
    path VARCHAR(255) PRIMARY KEY,
    queued_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Private activity history belonging to a user, with optional related-item and amount details.
CREATE TABLE User_Activity (
    activity_id BIGINT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    description VARCHAR(255) NOT NULL,
    action VARCHAR(40) NOT NULL DEFAULT 'UPDATE',
    related_item VARCHAR(180) NULL,
    amount DECIMAL(14,2) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_user_activity (user_id, activity_id),
    FOREIGN KEY (user_id) REFERENCES Users(user_id)
);

-- Login and signup audit events linked to the account that performed them.
CREATE TABLE Auth_Events (
    event_id BIGINT PRIMARY KEY AUTO_INCREMENT,
    user_id INT NOT NULL,
    event_type ENUM('LOGIN', 'SIGNUP') NOT NULL,
    occurred_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Links imported events to their original legacy log row without duplicating that reference.
    legacy_activity_id INT NULL UNIQUE,
    INDEX idx_auth_event_time (occurred_at, event_id),
    FOREIGN KEY (user_id) REFERENCES Users(user_id)
);

